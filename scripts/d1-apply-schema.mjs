#!/usr/bin/env node
/**
 * Generate the reviewed MEDBOT fresh-D1 schema (version 18) as a SQL file so
 * it can be applied to an empty D1 database with the official Wrangler
 * command:
 *
 *   npx wrangler d1 execute <database> --remote --file=<schema.sql>
 *
 * The schema source of truth remains src/db/d1/migrations.js (D1_SCHEMA_SQL).
 * This helper only materialises that reviewed contract; it does not define or
 * alter schema itself.
 *
 * Safety:
 * - never contacts Cloudflare;
 * - never opens or modifies a local SQLite database;
 * - never reads, writes or embeds secrets, account ids or database ids;
 * - refuses to overwrite an existing file unless --force is given;
 * - --check fails instead of writing when the file is out of date (CI gate).
 *
 * Usage:
 *   node scripts/d1-apply-schema.mjs --output ./artifacts/d1-schema.sql
 *   node scripts/d1-apply-schema.mjs --output ./artifacts/d1-schema.sql --check
 *   node scripts/d1-apply-schema.mjs --stdout
 */

import fs from 'node:fs';
import path from 'node:path';
import { D1_SCHEMA_VERSION, getD1SchemaSql } from '../src/db/d1/migrations.js';

function usage(message = '') {
  if (message) console.error(message);
  console.error(
    'Usage: node scripts/d1-apply-schema.mjs (--output <sql-path> | --stdout) [--check] [--force]',
  );
  process.exit(2);
}

function parseArgs(argv) {
  const args = { output: null, stdout: false, check: false, force: false };
  for (let i = 0; i < argv.length; i += 1) {
    const value = argv[i];
    if (value === '--stdout') { args.stdout = true; continue; }
    if (value === '--check') { args.check = true; continue; }
    if (value === '--force') { args.force = true; continue; }
    if (value === '--output') {
      const next = argv[i + 1];
      if (!next || next.startsWith('--')) usage('Missing value for --output');
      args.output = next;
      i += 1;
      continue;
    }
    usage(`Unknown argument: ${value}`);
  }
  if (args.output && args.stdout) usage('Choose either --output or --stdout, not both');
  if (!args.output && !args.stdout) usage('Provide --output <sql-path> or --stdout');
  return args;
}

export function buildSchemaFile() {
  const banner =
    `-- MEDBOT D1 schema v${D1_SCHEMA_VERSION} (generated by scripts/d1-apply-schema.mjs)\n` +
    '-- Source of truth: src/db/d1/migrations.js (D1_SCHEMA_SQL)\n' +
    '-- Apply with: npx wrangler d1 execute <database> --remote --file=<this file>\n\n';
  return banner + getD1SchemaSql();
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const sql = buildSchemaFile();

  if (args.stdout) {
    process.stdout.write(sql);
    return;
  }

  const outputPath = path.resolve(args.output);
  const exists = fs.existsSync(outputPath);
  const current = exists ? fs.readFileSync(outputPath, 'utf8') : null;

  if (exists && current === sql) {
    console.log(`D1 schema v${D1_SCHEMA_VERSION} already up to date: ${outputPath}`);
    return;
  }

  if (args.check) {
    console.error(
      exists
        ? `D1 schema file is stale and differs from v${D1_SCHEMA_VERSION}: ${outputPath}`
        : `D1 schema file is missing: ${outputPath}`,
    );
    process.exitCode = 1;
    return;
  }

  if (exists && !args.force) {
    console.error(`Refusing to overwrite existing file: ${outputPath} (use --force)`);
    process.exitCode = 1;
    return;
  }

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, sql);
  console.log(
    `D1 schema v${D1_SCHEMA_VERSION} written: ${outputPath} (${Buffer.byteLength(sql)} bytes)`,
  );
  console.log(`Apply: npx wrangler d1 execute <database> --remote --file=${path.relative(process.cwd(), outputPath)}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
